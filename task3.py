import math

try:
    r = float(input("Введите радиус шара r: "))
    p = float(input("Введите диагональ p отверстия: "))
    d = float(input("Введите диагональ d отверстия: "))
except ValueError:
    print("Ошибка: необходимо ввести числа!")
    exit()

if r <= 0 or p <= 0 or d <= 0:
    print("Ошибка: все значения должны быть положительными числами.")
else:
    r_in = (p * d) / (2 * math.sqrt(p * p + d * d))
    if r <= r_in:
        print(f"Шар пройдёт через отверстие (радиус вписанной окружности = {r_in:.4f})")
    else:
        print(f"Шар не пройдёт через отверстие (радиус вписанной окружности = {r_in:.4f})")